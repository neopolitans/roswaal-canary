/**
 * Saving a hand-written Luau file from its tab (1.1.0): the file only, and
 * only one the project already has that Roswaal did not write.
 */

import { mkdir, mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";

import { afterAll, beforeAll, describe, expect, it } from "vitest";

import type { OpenProject } from "../src/server/config.js";
import { writeSource } from "../src/server/documents.js";

let base: string;
let project: OpenProject;
const beside = () => path.join(base, "beside.luau");
const inside = (rel: string) => path.join(project.root, rel);

beforeAll(async () => {
	base = await mkdtemp(path.join(tmpdir(), "roswaal-source-"));
	const root = path.join(base, "project");
	await mkdir(path.join(root, "src"), { recursive: true });
	await writeFile(path.join(root, "src", "Hand.luau"), "return 1\n");
	await writeFile(
		path.join(root, "src", "Made.luau"),
		"--!strict\n-- Generated by Roswaal. Do not edit this file directly;\n-- roswaal-graph: g1\nreturn 2\n",
	);
	await writeFile(path.join(root, "src", "notes.txt"), "notes\n");
	await writeFile(path.join(base, "beside.luau"), "SECRET\n");
	project = { root } as OpenProject;
});

afterAll(async () => {
	await rm(base, { recursive: true, force: true });
});

describe("saving a Luau file from its tab", () => {
	it("writes a hand-written file", async () => {
		await writeSource(project, "src/Hand.luau", "return 3\n");
		expect(await readFile(inside("src/Hand.luau"), "utf8")).toBe("return 3\n");
	});

	it("refuses a file Roswaal wrote", async () => {
		await expect(writeSource(project, "src/Made.luau", "return 4\n")).rejects.toThrow(
			/change its graph/,
		);
		expect(await readFile(inside("src/Made.luau"), "utf8")).toContain("return 2");
	});

	it("refuses another kind of file, and a file the project does not have", async () => {
		await expect(writeSource(project, "src/notes.txt", "x")).rejects.toThrow(/\.luau or \.lua/);
		await expect(writeSource(project, "src/New.luau", "x")).rejects.toThrow(/not in the project/);
	});

	it("writes nothing outside the project, however the path is spelled", async () => {
		for (const spelling of ["../beside.luau", "src/../../beside.luau", beside()]) {
			await expect(writeSource(project, spelling, "PWNED"), spelling).rejects.toThrow();
		}
		expect(await readFile(beside(), "utf8")).toBe("SECRET\n");
	});
});
